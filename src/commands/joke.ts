function getRecentJokes(): string {
    if (jokeHistory.length === 0) {
        return "Предыдущих шуток пока нет.";
    }

    return jokeHistory
        .slice(-MAX_JOKE_HISTORY)
        .map(
            (joke, index) =>
                `${index + 1}. ${joke}`,
        )
        .join("\n");
}

function saveJoke(joke: string): void {
    jokeHistory.push(joke);

    if (jokeHistory.length > MAX_JOKE_HISTORY) {
        jokeHistory.shift();
    }
}

