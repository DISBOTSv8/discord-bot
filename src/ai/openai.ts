export interface StoredGuildMessage {
    id: string;
    guildId: string;
    channelId: string;
    channelName: string;
    userId: string;
    displayName: string;
    content: string;
    timestamp: number;
    referenceMessageId?: string;
    referenceUserId?: string;
}

const MAX_MESSAGES_PER_CHANNEL = 150;

const guildMessages = new Map<
    string,
    Map<string, StoredGuildMessage[]>
>();

export function saveGuildMessage(
    message: StoredGuildMessage,
): void {
    let channels =
        guildMessages.get(message.guildId);

    if (!channels) {
        channels = new Map();

        guildMessages.set(
            message.guildId,
            channels,
        );
    }

    let messages =
        channels.get(message.channelId);

    if (!messages) {
        messages = [];

        channels.set(
            message.channelId,
            messages,
        );
    }

    const existingIndex =
        messages.findIndex(
            item => item.id === message.id,
        );

    if (existingIndex !== -1) {
        messages[existingIndex] = message;
    } else {
        messages.push(message);
    }

    messages.sort(
        (a, b) =>
            a.timestamp - b.timestamp,
    );

    if (
        messages.length >
        MAX_MESSAGES_PER_CHANNEL
    ) {
        messages.splice(
            0,
            messages.length -
            MAX_MESSAGES_PER_CHANNEL,
        );
    }
}

export function getGuildContext(
    guildId: string,
    options?: {
        channelIds?: string[];
        limit?: number;
    },
): StoredGuildMessage[] {
    const channels =
        guildMessages.get(guildId);

    if (!channels) {
        return [];
    }

    const limit =
        options?.limit ??
        MAX_CONTEXT_MESSAGES;

    const channelIds =
        options?.channelIds;

    const messages =
        [...channels.entries()]
            .filter(
                ([channelId]) =>
                    !channelIds ||
                    channelIds.includes(
                        channelId,
                    ),
            )
            .flatMap(
                ([, channelMessages]) =>
                    channelMessages,
            );

    return messages
        .sort(
            (a, b) =>
                a.timestamp -
                b.timestamp,
        )
        .slice(-limit);
}